-- Persist the provider-created Pix charge on the ride so both participants can
-- recover it after reconnecting. The Pix payload is participant-protected by
-- the existing mototaxi_corridas RLS policies.
BEGIN;

ALTER TABLE public.mototaxi_corridas
  ADD COLUMN IF NOT EXISTS pix_payment_id text,
  ADD COLUMN IF NOT EXISTS pix_transaction_id uuid,
  ADD COLUMN IF NOT EXISTS pix_copy_paste text,
  ADD COLUMN IF NOT EXISTS pix_charge_status text,
  ADD COLUMN IF NOT EXISTS pix_charge_created_at timestamptz,
  ADD COLUMN IF NOT EXISTS pix_charge_expires_at timestamptz;

CREATE UNIQUE INDEX IF NOT EXISTS uq_mototaxi_corridas_pix_payment_id
  ON public.mototaxi_corridas (pix_payment_id)
  WHERE pix_payment_id IS NOT NULL;

COMMENT ON COLUMN public.mototaxi_corridas.pix_copy_paste IS
  'Mercado Pago dynamic Pix payload generated by the assigned provider; visible only to ride participants through RLS.';
COMMENT ON COLUMN public.mototaxi_corridas.pix_transaction_id IS
  'Idempotency/external-reference UUID used by payment-gateway and pagamentos_split.';
COMMENT ON COLUMN public.mototaxi_corridas.pix_charge_status IS
  'Last Mercado Pago status for the provider-created Pix charge; paid remains the authoritative ride terminal state.';

COMMIT;
